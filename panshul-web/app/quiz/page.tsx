"use client";

import { FormEvent, useState } from "react";
import Link from "next/link";
import { api } from "@/lib/api";
import { RequireAuth } from "@/components/RequireAuth";

type Difficulty = "easy" | "medium" | "hard";

type Question = {
  id: number;
  question: string;
  options: string[];
  correct_index: number;
  explanation: string;
};

type Quiz = {
  topic: string;
  difficulty: string;
  questions: Question[];
};

const SUGGESTIONS = ["Photosynthesis", "Fractions", "Newton's laws", "Indian freedom struggle"];

function normalizeQuiz(data: unknown, topic: string, difficulty: string): Quiz {
  const raw = (data ?? {}) as { topic?: unknown; difficulty?: unknown; questions?: unknown };
  if (!Array.isArray(raw.questions)) {
    throw new Error("The quiz did not come back as questions. Try again.");
  }
  const questions = raw.questions.flatMap((item, index) => {
    const question = (item ?? {}) as Record<string, unknown>;
    const options = Array.isArray(question.options) ? question.options.map(String) : [];
    const text = String(question.question ?? "").trim();
    if (!text || options.length < 2) return [];
    return [{
      id: typeof question.id === "number" ? question.id : index + 1,
      question: text,
      options,
      correct_index: typeof question.correct_index === "number" ? question.correct_index : 0,
      explanation: String(question.explanation ?? ""),
    }];
  });
  if (questions.length === 0) throw new Error("The quiz did not come back as questions. Try again.");
  return {
    topic: typeof raw.topic === "string" && raw.topic ? raw.topic : topic,
    difficulty: typeof raw.difficulty === "string" ? raw.difficulty : difficulty,
    questions,
  };
}

export default function QuizPage() {
  return (
    <div className="page">
      <p className="kicker">Quiz</p>
      <h1>Practice a topic. Keep the score.</h1>
      <p className="lede">Generated by the quiz agent, then saved on your account when you submit.</p>
      <div className="section">
        <RequireAuth>
          <QuizStudio />
        </RequireAuth>
      </div>
    </div>
  );
}

function QuizStudio() {
  const [topic, setTopic] = useState("Photosynthesis");
  const [difficulty, setDifficulty] = useState<Difficulty>("medium");
  const [quiz, setQuiz] = useState<Quiz | null>(null);
  const [answers, setAnswers] = useState<Record<number, number>>({});
  const [pending, setPending] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<{ correct: number; total: number; scorePct: number; saved: boolean } | null>(null);

  async function generate(event?: FormEvent) {
    event?.preventDefault();
    if (topic.trim().length < 2) {
      setError("Enter a topic with at least 2 characters.");
      return;
    }
    setPending(true);
    setError(null);
    setResult(null);
    setAnswers({});
    try {
      const data = await api<unknown>("/api/v1/quiz/generate", {
        method: "POST",
        body: JSON.stringify({ topic: topic.trim(), difficulty }),
      });
      setQuiz(normalizeQuiz(data, topic.trim(), difficulty));
    } catch (err) {
      setQuiz(null);
      setError(err instanceof Error ? err.message : "Could not generate a quiz.");
    } finally {
      setPending(false);
    }
  }

  async function submit() {
    if (!quiz) return;
    const unanswered = quiz.questions.some((question) => answers[question.id] === undefined);
    if (unanswered) {
      setError("Answer every question before submitting.");
      return;
    }
    const correct = quiz.questions.filter((question) => answers[question.id] === question.correct_index).length;
    const total = quiz.questions.length;
    setPending(true);
    setError(null);
    setResult({ correct, total, scorePct: Math.round((1000 * correct) / total) / 10, saved: false });
    try {
      const saved = await api<{ score_pct: number }>("/api/v1/quiz/submit", {
        method: "POST",
        body: JSON.stringify({ topic: topic.trim(), difficulty, total, correct }),
      });
      setResult({ correct, total, scorePct: saved.score_pct, saved: true });
    } catch (err) {
      setError(err instanceof Error ? err.message : "The score could not be saved.");
    } finally {
      setPending(false);
    }
  }

  return (
    <>
      <form className="card" onSubmit={generate}>
        <label className="field">
          <span>Topic</span>
          <input value={topic} onChange={(event) => setTopic(event.target.value)} maxLength={200} />
        </label>
        <div className="topic-chips">
          {SUGGESTIONS.map((suggestion) => (
            <button key={suggestion} type="button" className="chip" onClick={() => setTopic(suggestion)}>
              {suggestion}
            </button>
          ))}
        </div>
        <div className="seg" role="group" aria-label="Difficulty">
          {(["easy", "medium", "hard"] as const).map((level) => (
            <button key={level} type="button" className={difficulty === level ? "is-on" : undefined} onClick={() => setDifficulty(level)}>
              {level}
            </button>
          ))}
        </div>
        <button type="submit" className="btn btn-primary" disabled={pending}>
          {pending ? "Writing the quiz…" : "Generate quiz"}
        </button>
      </form>

      {error ? <p className="error" role="alert" style={{ margin: "16px 0 0" }}>{error}</p> : null}

      {result ? (
        <div className="card" style={{ marginTop: 16 }}>
          <p className="kicker">{result.saved ? "Saved" : "Scored"}</p>
          <p className="score">{result.scorePct}%</p>
          <p>{result.correct} of {result.total} correct.</p>
          <div className="row">
            <Link href="/progress" className="btn">View progress</Link>
          </div>
        </div>
      ) : null}

      {quiz ? (
        <div className="quiz-list">
          {quiz.questions.map((question, index) => (
            <fieldset key={`${question.id}-${index}`} className="card quiz-card">
              <legend><strong>{index + 1}. {question.question}</strong></legend>
              {question.options.map((option, optionIndex) => {
                const picked = answers[question.id] === optionIndex;
                const reveal = result !== null;
                const correct = optionIndex === question.correct_index;
                const className = [
                  "quiz-option",
                  !reveal && picked ? "is-picked" : "",
                  reveal && correct ? "is-correct" : "",
                  reveal && picked && !correct ? "is-wrong" : "",
                ].filter(Boolean).join(" ");
                return (
                  <button
                    key={option}
                    type="button"
                    className={className}
                    disabled={result !== null}
                    onClick={() => setAnswers((current) => ({ ...current, [question.id]: optionIndex }))}
                  >
                    {option}
                  </button>
                );
              })}
              {result && question.explanation ? <p className="explain">{question.explanation}</p> : null}
            </fieldset>
          ))}
          {result === null ? (
            <button type="button" className="btn btn-leaf" disabled={pending} onClick={() => void submit()}>
              {pending ? "Saving…" : "Submit answers"}
            </button>
          ) : null}
        </div>
      ) : null}
    </>
  );
}
